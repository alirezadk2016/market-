  function merge() {
    if (typeof RANGES === 'undefined') return;
    Object.keys(RANGES).forEach(key => {
      if (RANGE_TITLES[key]) (RANGES[key].fa = RANGES[key].fa || {}).title = RANGE_TITLES[key];
      (RANGES[key].items || []).forEach(item => {
        const entry = PIECES[item.note];
        if (entry) item.fa = Object.assign({}, entry);
        (item.variants || []).forEach(variant => {
          if (COLOURS[variant.color]) variant.colorFa = COLOURS[variant.color];
        });
      });
    });
    if (typeof BRANDS !== 'undefined') {
      Object.keys(HOUSES).forEach(name => { if (BRANDS[name]) BRANDS[name].fa = HOUSES[name]; });
    }
  }

